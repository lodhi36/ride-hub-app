export const getRiderTranslation = (lang: string = 'hi', key: string): string => {
  const currentLang = (lang as RiderLanguage) in riderTranslations ? (lang as RiderLanguage) : 'hi';
  if (riderTranslations[currentLang]?.[key]) {
    return riderTranslations[currentLang][key];
  }
  if (currentLang !== 'en' && riderTranslations['en']?.[key]) {
    return riderTranslations['en'][key];
  }
  if (riderTranslations['hi']?.[key]) {
    return riderTranslations['hi'][key];
  }
  return key;
};
